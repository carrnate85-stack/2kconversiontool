import assert from 'node:assert/strict';
import { configureStrandLightmap, configureStrandTangentRange, configureStrandSpecular, configureStrandCoverage } from '../web/renderer/strand-preview-fixes.mjs';
const texture = { name: 'hair_lightmap.dds', matrix: {}, updateMatrix() {},
  userData: { range: { min: [0.2, 0.1, 0, 1], max: [0.8, 0.9, 1, 1], mask: [1, 1, 1, 0] } } };
const material = { map: {}, userData: {}, onBeforeCompile(shader) { shader.baseRangePreserved = true; }, customProgramCacheKey: () => 'range-base' };
configureStrandLightmap(material, texture);
const shader = { uniforms: {}, vertexShader: '#include <uv_vertex>', fragmentShader: '#include <color_fragment>\n#include <lights_fragment_end>' };
material.onBeforeCompile(shader);
assert.equal(shader.baseRangePreserved, true);
assert.equal(shader.uniforms.nbaStrandLightmap.value, texture);
assert.ok(shader.fragmentShader.includes('nbaStrandLightMin + nbaStrandLightSample *'));
assert.ok(shader.fragmentShader.includes('reflectedLight.directDiffuse *='));
assert.ok(shader.fragmentShader.includes('reflectedLight.directSpecular *='));
assert.ok(shader.fragmentShader.includes('reflectedLight.indirectSpecular *='));
assert.ok(!shader.fragmentShader.includes('diffuseColor.rgb *='));
assert.ok(!shader.fragmentShader.includes('diffuseColor.a *='));
assert.equal(material.customProgramCacheKey(), 'range-base:nba-strand-lightmap-v2');
const uniforms = material.userData.strandLightmapUniforms;
material.onBeforeCompile = () => {};
material.customProgramCacheKey = () => 'range-base';
const replacement = { ...texture, name: 'replacement.dds', userData: {} };
configureStrandLightmap(material, replacement);
assert.equal(material.userData.strandLightmapUniforms, uniforms);
assert.equal(uniforms.nbaStrandLightmap.value, replacement);
assert.deepEqual(Array.from(uniforms.nbaStrandLightMask.value), [0, 0, 0, 0]);
configureStrandLightmap(material, null);
assert.equal(material.userData.strandLightmap, null);
material.anisotropyMap = texture;
material.onBeforeCompile = () => {};
material.customProgramCacheKey = () => 'range-base';
configureStrandLightmap(material, texture);
const chunk = 'vec3 anisotropyPolar = texture2D( anisotropyMap, vAnisotropyMapUv ).rgb;';
configureStrandTangentRange(material, texture, chunk);
const combined = { uniforms: {}, vertexShader: '#include <uv_vertex>', fragmentShader: '#include <color_fragment>\n#include <lights_physical_fragment>\n#include <lights_fragment_end>' };
material.onBeforeCompile(combined);
assert.equal(combined.uniforms.nbaStrandLightmap.value, texture);
assert.deepEqual(Array.from(combined.uniforms.nbaStrandTangentMin.value), Array.from(new Float32Array(texture.userData.range.min)));
assert.ok(combined.fragmentShader.includes('nbaStrandTangentSample * (nbaStrandTangentMax.rgb - nbaStrandTangentMin.rgb)'));
assert.ok(combined.fragmentShader.includes('reflectedLight.directSpecular *='));
assert.equal(material.customProgramCacheKey(), 'range-base:nba-strand-lightmap-v2:nba-strand-tangent-range-v1');
configureStrandSpecular(material, true);
const fiber = { uniforms: {}, vertexShader: '#include <uv_vertex>', fragmentShader: '#include <color_fragment>\n#include <lights_physical_fragment>\n#include <lights_fragment_end>' };
material.onBeforeCompile(fiber);
assert.ok(fiber.fragmentShader.includes('sqrt(clamp(diffuseColor.rgb, 0.0, 1.0))'));
assert.ok(fiber.fragmentShader.includes('reflectedLight.directSpecular *= nbaStrandSpecularTint'));
assert.ok(fiber.fragmentShader.includes('reflectedLight.indirectSpecular *= nbaStrandSpecularTint'));
assert.ok(fiber.fragmentShader.includes('nbaStrandTangentDecoded'));
assert.ok(fiber.fragmentShader.includes('nbaStrandResponse'));
assert.ok(!fiber.fragmentShader.includes('diffuseColor.a *='));
assert.ok(!fiber.fragmentShader.includes('diffuseColor.rgb *='));
assert.equal(material.customProgramCacheKey(), 'range-base:nba-strand-lightmap-v2:nba-strand-tangent-range-v1:nba-strand-specular-v1');
const untextured = { map: null, userData: {}, onBeforeCompile: () => {}, customProgramCacheKey: () => 'untextured' };
configureStrandSpecular(untextured, true);
assert.equal(untextured.userData.strandSpecularResponse, false);
assert.equal(untextured.customProgramCacheKey(), 'untextured');
configureStrandSpecular(untextured, false);
assert.equal(untextured.userData.strandSpecularResponse, false);
const cards = { map: {}, userData: {}, alphaTest: .035, transparent: true, depthWrite: false };
configureStrandCoverage(cards, true, true);
assert.equal(cards.transparent, false);
assert.equal(cards.depthWrite, true);
assert.equal(cards.alphaToCoverage, true);
assert.equal(cards.alphaTest, .035);
assert.equal(cards.userData.strandAlphaMode, 'coverage');
configureStrandCoverage(cards, true, false);
assert.equal(cards.alphaToCoverage, false);
assert.equal(cards.userData.strandAlphaMode, 'cutout');
cards.transparent = true;
cards.depthWrite = false;
configureStrandCoverage(cards, false, true);
assert.equal(cards.transparent, true);
assert.equal(cards.depthWrite, false);
assert.equal(cards.userData.strandAlphaMode, null);
configureStrandCoverage(untextured, true, true);
assert.equal(untextured.userData.strandAlphaMode, null);
console.log('Strand lightmap, tangent range, fiber specular, coverage fallback and shader composition passed.');
