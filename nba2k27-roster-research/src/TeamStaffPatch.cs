    static string Name(byte[] b,int offset){
        int end=offset;while(end<offset+40&&BitConverter.ToUInt16(b,end)!=0)end+=2;
        if(end==offset+40)throw new Exception("Staff name is too long.");
        string value=System.Text.Encoding.Unicode.GetString(b,offset,end-offset);
        foreach(char c in value)if(Char.IsControl(c)||Char.IsSurrogate(c))throw new Exception("Invalid staff name.");
        return value;
    }
    static long Number(byte[] b,int offset,int shift,int bits,bool signed){
        long value=0;for(int i=0;i<bits;i++){int n=offset*8+shift+i;if((b[n/8]&(1<<(n%8)))!=0)value|=1L<<i;}
        return signed&&value>=32768?value-65536:value;
    }
    static void ValidateNumber(byte[] before,byte[] after,int offset,int shift,int bits,long min,long max,bool signed,bool system){
        long a=Number(before,offset,shift,bits,signed),b=Number(after,offset,shift,bits,signed);
        if(a==b)return;
        if(b<min||b>max||(system&&b>7&&b!=15))throw new Exception("A staff value is outside its supported range.");
    }
